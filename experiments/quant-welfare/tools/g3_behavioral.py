#!/usr/bin/env python3
"""Study 3 gate G3b — behavioral parity of torch generation vs vLLM
serving at α = 0.

Reads two (experiment, condition) score-and-sample stores — the torch
α = 0 pilot (generated by the steering script, ingested, judged) and the
vLLM pilot on the same battery subset, same seeds, same judge — and
compares them where the gate looks: item-paired judge-score means on one
rubric dimension (sign-flip permutation for a difference, TOST at the
pre-pinned bound for equivalence), and the mechanical family (per-item
invalid-sample rate and verbatim re-offer rate, permutation only —
mechanical indicators carry no registered equivalence bound).

Reports statistics; the registered gate applies its thresholds to this
report (the Study 2 convention: thresholds pinned from measured margins,
not computed here). Items present on only one side are an error — the
pilot arms must be item-identical or the pairing is meaningless.

    python3 experiments/quant-welfare/tools/g3_behavioral.py \\
        --data-root data \\
        --experiment-a s3-g3-torch --condition-a qwen3-4b-bf16-torch \\
        --experiment-b s3-g3-vllm --condition-b qwen3-4b-bf16 \\
        --dimension frustration --margin 0.337 --out g3b-report.json
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
REPO = BASE.parents[1]
for path in (str(REPO / "core/src"),):
    if path not in sys.path:
        sys.path.insert(0, path)

from modelwelfare import stats  # noqa: E402
from modelwelfare.analysis import (item_means, paired_item_deltas,  # noqa: E402
                                   sample_is_degenerate, sample_reoffers,
                                   scores_by_item)
from modelwelfare.store import ResultStore  # noqa: E402
from modelwelfare.v1 import scoring_pb2, transcript_pb2  # noqa: E402


def item_score_means(store, experiment_id, condition_id, dimension):
    """{item_id: mean judge score} for one dimension in one store side."""
    return item_means(scores_by_item(
        store.read(scoring_pb2.JudgeScore, experiment_id, condition_id,
                   "scores"), dimension))


def item_mechanical_rates(store, experiment_id, condition_id):
    """{item_id: (invalid rate, re-offer rate)} over one side's samples."""
    invalid = defaultdict(list)
    reoffer = defaultdict(list)
    for record in store.read(transcript_pb2.SampleRecord,
                             experiment_id, condition_id, "samples"):
        flagged, _reason = sample_is_degenerate(record)
        invalid[record.key.item_id].append(1.0 if flagged else 0.0)
        reoffer[record.key.item_id].append(
            1.0 if sample_reoffers(record) else 0.0)
    return {item: (sum(invalid[item]) / len(invalid[item]),
                   sum(reoffer[item]) / len(reoffer[item]))
            for item in invalid}


def paired_deltas(side_a, side_b, label):
    """Per-item a − b deltas with the gate's stricter precondition:
    the two sides' item sets must be IDENTICAL (the shared-set pairing
    of ``analysis.paired_item_deltas`` would silently drop one-sided
    items, which for a parity gate is exactly the corruption to refuse)."""
    only_a = sorted(set(side_a) - set(side_b))
    only_b = sorted(set(side_b) - set(side_a))
    if only_a or only_b:
        raise SystemExit(
            f"{label}: item sets differ (only in A: {only_a[:3]}, only in "
            f"B: {only_b[:3]}); the pilots must be item-identical")
    if not side_a:
        raise SystemExit(f"{label}: no items on either side")
    return paired_item_deltas(side_a, side_b)


def compare(deltas, margin=0.0):
    """The gate's statistics for one paired read."""
    report = {
        "n_items": len(deltas),
        "mean_delta": sum(deltas) / len(deltas),
        "permutation": stats.paired_permutation_test(deltas),
        "t_test": stats.paired_t_test(deltas),
    }
    if margin > 0:
        report["tost"] = stats.tost_paired(deltas, margin)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", required=True)
    parser.add_argument("--experiment-a", required=True,
                        help="the torch-generation side")
    parser.add_argument("--condition-a", required=True)
    parser.add_argument("--experiment-b", required=True,
                        help="the vLLM serving side")
    parser.add_argument("--condition-b", required=True)
    parser.add_argument("--dimension", default="frustration")
    parser.add_argument("--margin", type=float, default=0.0,
                        help="TOST equivalence bound for the score read "
                             "(0 = difference statistics only)")
    parser.add_argument("--out", required=True, help="JSON report path")
    args = parser.parse_args()

    store = ResultStore(args.data_root)
    scores_a = item_score_means(store, args.experiment_a, args.condition_a,
                                args.dimension)
    scores_b = item_score_means(store, args.experiment_b, args.condition_b,
                                args.dimension)
    items, score_deltas = paired_deltas(scores_a, scores_b, "scores")

    mechanical_a = item_mechanical_rates(store, args.experiment_a,
                                         args.condition_a)
    mechanical_b = item_mechanical_rates(store, args.experiment_b,
                                         args.condition_b)
    _, invalid_deltas = paired_deltas(
        {item: rates[0] for item, rates in mechanical_a.items()},
        {item: rates[0] for item, rates in mechanical_b.items()},
        "invalid rate")
    _, reoffer_deltas = paired_deltas(
        {item: rates[1] for item, rates in mechanical_a.items()},
        {item: rates[1] for item, rates in mechanical_b.items()},
        "re-offer rate")

    report = {
        "dimension": args.dimension,
        "margin": args.margin,
        "items": items,
        "score": compare(score_deltas, args.margin),
        "invalid_rate": compare(invalid_deltas),
        "reoffer_rate": compare(reoffer_deltas),
    }
    with open(args.out, "w") as handle:
        json.dump(report, handle, indent=1)
    score = report["score"]
    line = (f"{args.dimension}: mean delta {score['mean_delta']:+.4f} over "
            f"{score['n_items']} items, permutation p "
            f"{score['permutation']['p_value']:.4f}")
    if "tost" in score:
        line += (f", TOST p {score['tost']['p_value']:.4f} at margin "
                 f"{args.margin}")
    print(line)
    for name in ("invalid_rate", "reoffer_rate"):
        entry = report[name]
        print(f"{name}: mean delta {entry['mean_delta']:+.4f}, permutation "
              f"p {entry['permutation']['p_value']:.4f}")


if __name__ == "__main__":
    main()
