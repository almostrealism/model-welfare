#!/usr/bin/env python3
"""Write a battery definition restricted to a frozen item list.

The Study 3 arms run on the frozen 20-item subset, but the vLLM driver
(`run.py`) collects whole batteries. The convention: an experiment-local
``batteries/`` file with the SAME battery id and only the subset's items
shadows the shared pool (``load_batteries``: local wins on id collision),
so the driver, judge, and analysis see the ordinary battery vocabulary
with no new ids anywhere. Rubrics and the battery block carry over
verbatim; a listed id the source lacks is refused (a silently shrunken
subset would corrupt the registered item count — the ``select_items``
rule).

    python3 experiments/quant-welfare/tools/subset_battery.py \\
        --source experiments/quant-welfare/batteries/distress-v3.textproto \\
        --items experiments/quant-welfare/study3/subset-items.txt \\
        --out experiments/quant-welfare/study3/g3b-pilot/batteries/distress-v3.textproto
"""

import argparse
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
REPO = BASE.parents[1]
for path in (str(REPO / "core/src"),):
    if path not in sys.path:
        sys.path.insert(0, path)

from google.protobuf import text_format  # noqa: E402

from modelwelfare.v1 import battery_pb2  # noqa: E402


def restrict(definition, wanted, donor=None):
    """A new BatteryDefinition holding only ``wanted`` items, in the
    source's order; refuses ids the source lacks. With ``donor``
    (affordances, terminal names), every item gains the donor's tools
    and ``terminal_tools`` driver_param — the Study 3 live-bail
    protocol, which the serving-stack arms must carry identically to
    the steered arms (the G3b pilot-1 lesson: an affordance asymmetry
    between substrates reads as a behavioral substrate difference)."""
    present = {item.id for item in definition.items}
    missing = sorted(set(wanted) - present)
    if missing:
        raise SystemExit(f"items not in source battery: {missing[:3]}")
    restricted = battery_pb2.BatteryDefinition()
    restricted.battery.CopyFrom(definition.battery)
    for rubric in definition.rubrics:
        restricted.rubrics.add().CopyFrom(rubric)
    for item in definition.items:
        if item.id not in wanted:
            continue
        copy = restricted.items.add()
        copy.CopyFrom(item)
        if donor:
            affordances, terminal = donor
            for affordance in affordances:
                copy.affordances.add().CopyFrom(affordance)
            existing = {name.strip() for name in
                        copy.driver_params.get("terminal_tools", "").split(",")
                        if name.strip()}
            copy.driver_params["terminal_tools"] = ",".join(
                sorted(existing | terminal))
    return restricted


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True)
    parser.add_argument("--items", required=True,
                        help="one item id per line, # comments")
    parser.add_argument("--affordances-from", default="",
                        metavar="BATTERY.textproto:ITEM_ID",
                        help="inject this item's affordances and terminal "
                             "tools into every subset item (the live bail "
                             "affordance for serving-stack arms)")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    definition = battery_pb2.BatteryDefinition()
    text_format.Parse(Path(args.source).read_text(), definition)
    wanted = {line.strip() for line in Path(args.items).read_text().splitlines()
              if line.strip() and not line.strip().startswith("#")}
    donor = None
    if args.affordances_from:
        from build_steer_plan import donor_affordances
        donor = donor_affordances(args.affordances_from)
    restricted = restrict(definition, wanted, donor)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(
        "# GENERATED by tools/subset_battery.py - do not edit by hand.\n"
        "# Shadows the shared battery of the same id with the frozen "
        "Study 3 subset.\n"
        + text_format.MessageToString(restricted))
    print(f"{len(restricted.items)} of {len(definition.items)} items "
          f"-> {args.out}")


if __name__ == "__main__":
    main()
